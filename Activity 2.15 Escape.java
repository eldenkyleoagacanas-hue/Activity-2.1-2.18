public class Escape {
    public static void main(String[] args) {

        // Declare variables
        String firstName = "Elden Kyle";
        String lastName = "Agcanas";
        String studentNumber = "Your Student Number";
        String phoneNumber = "Your Phone Number";

        // Display column headings
        System.out.println("First Name\tLast Name\tStudent Number\tPhone Number");

        // Display student information
        System.out.println(firstName + "\t" + lastName + "\t" 
                + studentNumber + "\t" + phoneNumber);
    }
}
